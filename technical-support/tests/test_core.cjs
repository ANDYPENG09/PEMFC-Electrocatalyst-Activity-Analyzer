'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const core = html.match(/<script id="core">([\s\S]*?)<\/script>/);
assert.ok(core, 'inline core exists');
const context = {module:{exports:{}}, Number, String, Set, Math, Error};
vm.runInNewContext(core[1], context);
const C = context.module.exports;
const head = 'sample_id,ecsa_m2_g,ehalf_V,jlim_mA_cm2,ma_0_9V_A_mg,sa_0_9V_mA_cm2_Pt,tafel_mV_dec,qc_status';
let records=C.importCSV('\ufeff'+head+'\r\n"Example, 1",42.1,.88,-5.5,0.2,0.3,,Check recommended\r\n');
const fixture = C.importCSV(fs.readFileSync('examples/analyzer-synthetic-results.csv', 'utf8'));
assert.equal(fixture.length, 2);
assert.ok(fixture.every(x => x.origin === 'imported' && x.qc === 'Good'));
assert.equal(records.length,1);assert.equal(records[0].id,'Example, 1');assert.equal(records[0].metrics.tafel_mV_dec,null);assert.equal(records[0].qc,'Check recommended');
assert.equal(C.importCSV(head+'\n"x""y",1,.8,-5,1,1,1,Good')[0].id,'x"y');
assert.throws(()=>C.importCSV(head+'\nx,1,.8,-5,1,1,1,Good\nx,1,.8,-5,1,1,1,Good'),/Duplicate/);
assert.throws(()=>C.importCSV('sample_id,qc_status\nx,Good'),/Missing results.csv/);
assert.throws(()=>C.importCSV(head+'\nx,NaN,.8,-5,1,1,1,Good'),/Invalid ecsa/);
assert.throws(()=>C.importCSV(head+'\nx,1,.8,-5,1,1,1,pass'),/Unknown qc_status/);
assert.throws(()=>C.importCSV(head+'\n"x,1,.8,-5,1,1,1,Good'),/Unclosed/);
assert.throws(()=>C.importCSV(head+'\nx,1,.8,-5,1,1,1,Good,unexpected'),/wrong number/);
let meta={method:'M1',electrolyte:'0.1 M',rpm:'1600',loading:'20',temperature:'25',scan:'20',correction:'RHE',background:'N2'};
let a={id:'a',qc:'Good',origin:'synthetic',meta:{...meta}}, b={id:'b',qc:'Good',origin:'synthetic',meta:{...meta}};
assert.equal(C.comparison(a,b).ok,true);
assert.equal(C.comparison(a,{...b,meta:{...meta,rpm:''}}).ok,false);
assert.equal(C.comparison(a,{...b,meta:{...meta,rpm:'0x640'}}).ok,false);
assert.equal(C.comparison(a,{...b,meta:{...meta,rpm:'900'}}).ok,false);
assert.equal(C.comparison(a,{...b,qc:'Invalid'}).reason,'invalid');
assert.equal(C.comparison(a,{...b,origin:'anonymized'}).reason,'origin');
assert.equal(C.comparison(a,{...b,id:'a'}).reason,'same');
const d=C.difference('jlim_mA_cm2',-4.7,-5.8);assert.ok(Math.abs(d.pct-(-18.965517241))<1e-8);assert.ok(Math.abs(d.diff-1.1)<1e-9);
assert.equal(C.difference('jlim_mA_cm2',4.7,-5.8),null);
assert.equal(C.difference('ecsa_m2_g',3,0).pct,null);
assert.equal(C.difference('ecsa_m2_g',null,1),null);
assert.equal(C.specification(-4.7,'-6.3','-5.5','Good').status,'outside');
assert.equal(C.specification(-5.8,'-6.3','-5.5','Good').status,'within');
assert.equal(C.specification(-5.8,'-5','-6','Good').status,'invalid_limits');
assert.equal(C.specification(-5.8,'garbage','','Good').status,'invalid_limits');
assert.equal(C.specification(null,'-6','','Good').status,'missing_value');
assert.equal(C.specification(-5.8,'-6','','Invalid').status,'invalid_data');
assert.equal(C.specification(-5.8,'','','Good').status,'missing');
console.log('Core tests passed: CSV, QC, comparability, signed current, specifications.');
